import {chromium,expect} from '@playwright/test';
import {mkdir,writeFile} from 'node:fs/promises';
import path from 'node:path';
const base=process.env.SWARMOPS_URL||'http://127.0.0.1:8765';
const output=path.resolve('../docs/images');
await mkdir(output,{recursive:true});
const checks=[],errors=[];
let browser;
try{
 browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1512,height:1100},deviceScaleFactor:1});
 page.on('pageerror',error=>errors.push(error.message));
 const state=async()=> (await (await page.request.get(base+'/api/state')).json());
 const command=async data=>{const response=await page.request.post(base+'/api/command',{data});expect(response.ok()).toBeTruthy();return response.json();};
 await command({action:'preset',preset:'closure',seed:7});
 await page.goto(base);
 await expect(page.getByRole('heading',{name:'Every robot. One shared floor.'})).toBeVisible();
 await expect(page.locator('svg.warehouse')).toHaveCount(2);
 await page.getByRole('button',{name:'Step +1',exact:true}).click();
 await expect.poll(async()=> (await state()).runs[0].summary.tick).toBe(1);
 checks.push('real SSE state, two warehouse views, single tick');
 await page.getByRole('button',{name:'▶ Play',exact:true}).click();
 await expect.poll(async()=> (await state()).runs[0].summary.tick).toBeGreaterThan(2);
 await page.getByRole('button',{name:'Ⅱ Pause',exact:true}).click();
 const paused=await state();await page.waitForTimeout(250);
 expect((await state()).runs[0].summary.tick).toBe(paused.runs[0].summary.tick);
 checks.push('server clock, play and pause');
 await page.getByLabel('Compare to ML').uncheck();await expect(page.locator('svg.warehouse')).toHaveCount(1);
 await page.getByLabel('Compare to ML').check();await expect(page.locator('svg.warehouse')).toHaveCount(2);
 await page.getByLabel('Occupancy heatmap').check();
 for(let i=0;i<40;i++)await command({action:'step'});
 await expect(page.locator('.run-status')).toContainText(`tick ${paused.runs[0].summary.tick+40}`);
 await page.screenshot({path:path.join(output,'console.png'),fullPage:true});
 checks.push('comparison, heatmap, and real screenshot');
 const trace=await (await page.request.get(base+'/api/export/trace')).json();
 expect(trace.runs[0].trace.length).toBeGreaterThan(30);expect(trace.model_id).toHaveLength(64);
 const scenario=await (await page.request.get(base+'/api/export/scenario')).json();
 await command({action:'scenario',scenario});
 await expect(page.locator('.run-status')).toContainText('tick 0');
 checks.push('trace/model identity export and scenario import reset');
 await page.getByRole('button',{name:/Model insights/}).click();
 await expect(page.getByRole('heading',{name:'A duration estimate. Not a promise.'})).toBeVisible();
 await expect(page.locator('.result-bars')).toContainText('2192');
 await page.screenshot({path:path.join(output,'model.png'),fullPage:true});
 checks.push('model metadata and frozen measured results');
 await page.getByRole('button',{name:/Scenario editor/}).click();
 await page.getByRole('button',{name:'Start editing',exact:true}).click();
 const map=page.locator('svg.warehouse').first(),box=await map.boundingBox();
 await map.click({position:{x:box.width*4.2/(scenario.width+1.4),y:box.height*4.2/(scenario.height+1.4)}});
 await page.getByRole('button',{name:'Validate & apply',exact:true}).click();
 await expect(page.getByRole('button',{name:'Start editing',exact:true})).toBeVisible();
 const edited=await (await page.request.get(base+'/api/export/scenario')).json();
 expect(edited.walls.length).not.toBe(scenario.walls.length);
 checks.push('map draft editing, validation and safe reset');
 await page.getByRole('button',{name:/Experiments/}).click();
 await page.getByRole('button',{name:'Run comparison ↗',exact:true}).click();
 await page.getByRole('button',{name:'Cancel experiment',exact:true}).click();
 await expect(page.getByRole('status')).toContainText(/CANCELLED|COMPLETE/);
 await page.getByRole('button',{name:'Run comparison ↗',exact:true}).click();
 await expect(page.getByRole('status')).toContainText('COMPLETE',{timeout:15000});
 await expect(page.locator('tbody tr')).toHaveCount(3);
 checks.push('background comparison, cancellation and results');
 await page.getByRole('button',{name:/Fleet console/}).click();
 await page.getByLabel('Scenario preset').selectOption('light');
 await page.getByLabel('Scenario seed').fill('42');
 await page.getByRole('button',{name:'Load scenario',exact:true}).click();
 await expect.poll(async()=> (await state()).scenario.seed).toBe(42);
 await page.reload();await expect(page.getByLabel('Scenario seed')).toHaveValue('42');
 checks.push('seed controls and reload persistence');
 await page.setViewportSize({width:780,height:1000});
 await page.screenshot({path:path.join(output,'console-compact.png'),fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
 checks.push('compact layout without horizontal overflow');
 expect(errors).toEqual([]);
 await writeFile('../results/browser.json',JSON.stringify({passed:true,checks,pageErrors:errors},null,2)+'\n');
 console.log(JSON.stringify({passed:true,checks},null,2));
}catch(error){
 await writeFile('../results/browser.json',JSON.stringify({passed:false,checks,pageErrors:errors,error:String(error)},null,2)+'\n');
 throw error;
}finally{if(browser)await browser.close();}
